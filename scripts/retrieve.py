def get_modalities(text, cards):
    """根据症状词与命中证型名，返回建议的非药物疗法列表（与用药并列）。"""
    norm = normalize(text)
    found, seen = [], set()
    for kws, mods in MODALITY_TRIGGERS:
        if any(kw_match_signal(k, norm) for k in kws):
            for m in mods:
                if m not in seen:
                    seen.add(m)
                    found.append(m)
    for c in (cards or []):
        syn = c.get("syndrome", "")
        for kws, mods in MODALITY_TRIGGERS:
            if any(kw_match_signal(k, syn) for k in kws):
                for m in mods:
                    if m not in seen:
                        seen.add(m)
                        found.append(m)
    return found


