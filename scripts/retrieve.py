def get_western_meds(text, cards):
    """根据症状词与命中证型，返回常规西药参考提示列表（只讲类别与方向，须医生指导）。"""
    norm = normalize(text)
    found, seen = [], set()
    for kws, meds in WESTERN_MEDS:
        if any(kw_match_signal(k, norm) for k in kws):
            for m in meds:
                if m not in seen:
                    seen.add(m)
                    found.append(m)
    return found


def detect_dept(text):
    """按专科指示词识别所属科室；命中即优先用该科词典。
    指示词多为专业术语单字（疮、痈、痹等），误伤概率低，用子串匹配保留召回。"""
    norm = normalize(text)
    hits = {}
    for dept, inds in DEPT_INDICATORS.items():
        for i in inds:
            if i in norm:
                hits[dept] = hits.get(dept, 0) + 1
                break
    if not hits:
        return None
    return max(hits.items(), key=lambda kv: kv[1])[0]


def find_rep_formula(syndrome):
    """在 SYNDROME_FORMULA 中选最长命中的关键词，避免短词（如"血瘀"）抢先匹配。"""
    best = None
    for kw, fo in SYNDROME_FORMULA:
        if kw in syndrome and (best is None or len(kw) > len(best[0])):
            best = (kw, fo)
    return best[1] if best else None


def zh_label(name):
    """把带编号与扩展名的文件名转成纯中文书名或分册名，避免输出拉丁字母。"""
    s = re.sub(r"[^\u4e00-\u9fff]", "", str(name or ""))
    return "《" + s + "》" if s else "书名待核"


def zh_source(text):
    """把证型卡片依据里的分册编号转成中文，并清除残留拉丁字符。"""
    s = re.sub(r"references\s*/\s*(\d+)", lambda m: "深读分册第" + m.group(1) + "册", str(text or ""))
    s = re.sub(r"[A-Za-z/]", "", s)
    return s.strip()


def zh_text(text):
    """检索片段只保留中文与标点数字，清除转义标记和拉丁字母。"""
    s = re.sub(r"\\[A-Za-z]+", "", str(text or ""))
    return re.sub(r"[A-Za-z]", "", s)


def search_refs(terms, top=5):
    hits = []
    if not os.path.isdir(REFS_DIR):
        return hits
    files = [f for f in os.listdir(REFS_DIR) if f.endswith(".md")]
    for fn in files:
        path = os.path.join(REFS_DIR, fn)
        try:
            with open(path, "r", encoding="utf-8") as fh:
                for i, line in enumerate(fh, 1):
                    if any(t in line for t in terms):
                        s = zh_text(line.strip())
                        if len(s) > 120:
                            s = s[:120] + "…"
                        hits.append({"file": fn, "line": i, "text": s})
                        if len(hits) >= top * 6:
                            break
        except Exception:
            continue
    return hits[:top * 6]


def parse_corpus_meta(path):
    meta = {"书名": "", "作者": "", "朝代": ""}
    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as fh:
            for _ in range(8):
                line = fh.readline()
                if not line:
                    break
                for key in ("书名", "作者", "朝代"):
                    if key in line and not meta[key]:
                        # 形如 书名：本草纲目
                        m = re.search(key + r"[：:]\s*([^\n]+)", line)
                        if m:
                            meta[key] = m.group(1).strip()
    except Exception:
        pass
    return meta


def search_corpus(terms, corpus_dir, top=5):
    """委托给带倒排索引的 corpus_search 模块；corpus_dir 仅用于判断是否启用。"""
    if not corpus_dir or not os.path.isdir(corpus_dir):
        return [], False
    query = " ".join(terms) if isinstance(terms, (list, set, tuple)) else str(terms)
    try:
        raw = corpus_search.search_corpus(query, top=top, use_index=True)
    except Exception:
        raw = []
    out = []
    for h in raw:
        for ln in h.get("lines", []):
            out.append({
                "book": h.get("title") or h.get("file"),
                "author": h.get("author", ""),
                "dynasty": h.get("dynasty", ""),
                "file": h.get("file", ""),
                "line": 0,
                "text": zh_text(ln),
            })
    return out[:top], True


