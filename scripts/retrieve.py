def main():
    ap = argparse.ArgumentParser(description="中医症状驱动检索脚本")
    ap.add_argument("query", help="症状描述文本")
    ap.add_argument("--corpus", default=DEFAULT_CORPUS, help="848 本语料目录")
    ap.add_argument("--top", type=int, default=5, help="每类返回条数")
    ap.add_argument("--json", action="store_true", help="输出 JSON")
    args = ap.parse_args()

    query = args.query
    flags = check_redflags(query)
    cards = match_symptoms(query)

    # 检索词：取命中卡片的关键词 + 原始词切分
    terms = set()
    for c in cards:
        terms.update(c["matched"])
    norm = normalize(query)
    for tok in norm.split():
        if len(tok) >= 2:
            terms.add(tok)
    terms = [t for t in terms if len(t) >= 2]

    ref_hits = search_refs(terms, top=args.top)
    corpus_hits, corpus_used = search_corpus(terms, args.corpus, top=args.top)

    # 交叉验证：对 top 证型的代表方做图谱核对
    cross = None
    if cards:
        rep_formula = find_rep_formula(cards[0]["syndrome"]) if cards else None
        if rep_formula:
            try:
                cross = verify_graph.cross_validate(formula_zh=rep_formula, syndrome=cards[0]["syndrome"])
            except Exception:
                cross = None

    if args.json:
        out = {
            "query": query,
            "red_flags": flags,
            "candidates": cards[:6],
            "ref_hits": ref_hits[:12],
            "corpus_used": corpus_used,
            "corpus_hits": corpus_hits[:10],
            "cross_validate": cross,
        }
        print(json.dumps(out, ensure_ascii=False, indent=2))
    else:
        print(build_draft(query, flags, cards, ref_hits, corpus_hits, corpus_used))


if __name__ == "__main__":
    main()
