def detect_tests(text):
    """识别用户提到的西医检查术语，返回命中的术语解读列表（保持原表顺序，去重）。
    匹配时去除空格，兼容"X光"与"X 光"等带空格写法；纯字母关键词做字母边界检查，
    避免"ct"误命中"tct"这类子串误配；重叠命中时以更长的关键词为准，
    避免"x光透视"同时命中拍片与透视两项。"""
    compact = re.sub(r"\s+", "", normalize(text))
    hits = []  # (关键词长度, 起点, 终点, 表序号)
    for idx, (kws, info) in enumerate(MEDICAL_TESTS):
        best = None
        for k in kws:
            if re.fullmatch(r"[a-z]+", k):
                m = re.search(r"(?<![a-z])" + re.escape(k) + r"(?![a-z])", compact)
            else:
                m = re.search(re.escape(k), compact)
            if m and (best is None or len(k) > len(best[0])):
                best = (k, m.start(), m.end())
        if best:
            hits.append((len(best[0]), best[1], best[2], idx, info))
    hits.sort(key=lambda h: (-h[0], h[1]))
    kept_idx, occupied = [], []
    for hlen, s, e, idx, info in hits:
        if any(not (e <= os or s >= oe) for os, oe in occupied):
            continue
        kept_idx.append(idx)
        occupied.append((s, e))
    kept_idx.sort()
    return [MEDICAL_TESTS[i][1] for i in kept_idx]


