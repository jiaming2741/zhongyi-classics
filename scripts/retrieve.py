def normalize(text):
    """去掉常见标点，保留中文与数字字母。"""
    text = text.lower()
    for ch in "，。、；：？！,.;:?!（）()【】《》<>~@#%&*=+|/":
        text = text.replace(ch, " ")
    text = text.replace('"', " ").replace("'", " ").replace("\\", " ").replace("`", " ")
